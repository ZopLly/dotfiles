#!/usr/bin/env python3
"""Generate small lockscreen token files from existing palette and Niri outline."""
from pathlib import Path
import argparse,re
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
for name in ('ancient-odyssey','catppuccin-mocha','gruvbox-dark','tokyo-night'):
    root=ROOT/'assets/themes'/name
    colors=dict(re.findall(r'@define-color\s+(\w+)\s+(#[\da-fA-F]+)',(root/'waybar.css').read_text()))
    outline=re.search(r'active-color\s+"(#[\da-fA-F]+)"',(root/'niri-runtime.kdl').read_text())
    values={key:colors.get(source,default) for key,source,default in [('fg','fg','#F3E7D0'),('dim','fg_dim','#D9CCB8'),('bg','bg','#17283A'),('surface','surface','#203447'),('accent','accent','#81B5D5'),('border','accent','#D8C6AA'),('error','power_color','#F08C86')]}
    values['surface']=colors.get('surface',colors.get('bg_modules',values['bg']))
    def rgb(value):return [int(value[i:i+2],16) for i in (1,3,5)]
    def luminance(value):
        channels=[v/255 for v in rgb(value)]
        return sum(w*(v/12.92 if v<=0.04045 else ((v+0.055)/1.055)**2.4) for w,v in zip((0.2126,0.7152,0.0722),channels))
    def contrast(a,b):
        x,y=sorted((luminance(a),luminance(b)))
        return (y+0.05)/(x+0.05)
    original=rgb(values['dim']); primary=rgb(values['fg'])
    for step in range(11):
        if min(contrast(values['dim'],values['bg']),contrast(values['dim'],values['surface']))>=4.5:break
        factor=(step+1)/10
        values['dim']='#'+''.join(f'{round(a+(b-a)*min(factor,1)):02x}' for a,b in zip(original,primary))
    if outline:values['border']=outline.group(1)
    bg=values['bg'].lstrip('#'); rgb=[int(bg[i:i+2],16) for i in (0,2,4)]
    alpha=round(0.16+sum(rgb)/765*0.45,2)
    values['overlay']=f'rgba({rgb[0]}, {rgb[1]}, {rgb[2]}, {alpha})'
    content='/* Generated by scripts/lockscreen-tokens.py from shared theme sources. */\n'+''.join(f'@define-color lock_{key} {value};\n' for key,value in values.items())+'@import url("../../../gtklock/minimal.css");\n'
    target=root/'gtklock.css'
    if args.check:
        if target.read_text()!=content:raise SystemExit('Outdated tokens: '+name)
    else:target.write_text(content)
